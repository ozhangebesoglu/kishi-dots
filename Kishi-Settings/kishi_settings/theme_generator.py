    def apply_powermenu_theme(self):
        """Rofi powermenu temalarını güncelle (SUPER+L)"""
        powermenu_dir = f"{self.config_path}/rofi/powermenu"
        
        try:
            if not os.path.exists(powermenu_dir):
                print(f"  Powermenu dizini bulunamadı: {powermenu_dir}")
                return False

            import re
            updated_count = 0

            # Tüm powermenu type klasörlerini tara
            for type_folder in os.listdir(powermenu_dir):
                type_path = os.path.join(powermenu_dir, type_folder)
                if not os.path.isdir(type_path):
                    continue

                # Her style dosyasını güncelle
                for style_file in os.listdir(type_path):
                    if style_file.endswith('.rasi'):
                        style_path = os.path.join(type_path, style_file)
                        self._update_rofi_style_file(style_path)
                        updated_count += 1

            print(f"  Powermenu: {updated_count} stil dosyası güncellendi")
            return True

        except Exception as e:
            print(f"  Powermenu tema uygulama hatası: {e}")
            return False

