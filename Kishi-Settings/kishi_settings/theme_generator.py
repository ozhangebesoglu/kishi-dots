    def apply_hyprland_theme(self):
        """Hyprland temasını uygula"""
        colors_path = f"{self.config_path}/hypr/themes/{self.theme_name}_colors.conf"
        hyprland_conf = f"{self.config_path}/hypr/hyprland.conf"

        # hyprland.conf'a source satırı ekle veya güncelle
        source_line = f"source = ~/.config/hypr/themes/{self.theme_name}_colors.conf"

        try:
            # Mevcut config'i oku
            with open(hyprland_conf, 'r') as f:
                content = f.read()

            # Eski wallpaper tema source'unu kaldır
            lines = content.split('\n')
            new_lines = []
            for line in lines:
                if 'source' in line and 'themes/wallpaper_' in line and '_colors.conf' in line:
                    continue  # Eski tema source'unu atla
                new_lines.append(line)

            # Yeni source'u ekle (dosyanın başına)
            new_content = '\n'.join(new_lines)
            if source_line not in new_content:
                # İlk source satırından sonra ekle
                insert_pos = new_content.find('source')
                if insert_pos != -1:
                    end_of_line = new_content.find('\n', insert_pos)
                    new_content = new_content[:end_of_line+1] + source_line + '\n' + new_content[end_of_line+1:]
                else:
                    new_content = source_line + '\n' + new_content

            # Kaydet
            with open(hyprland_conf, 'w') as f:
                f.write(new_content)

            # Hyprctl ile reload
            subprocess.run(['hyprctl', 'reload'], capture_output=True)
            print("  Hyprland tema uygulandı ve reload edildi")
            return True

        except Exception as e:
            print(f"  Hyprland tema uygulama hatası: {e}")
            return False

    def apply_waybar_theme(self):
        """Waybar temasını uygula - style.css'deki renk değişkenlerini güncelle"""
        style_path = f"{self.config_path}/waybar/style.css"

        try:
            if not os.path.exists(style_path):
                print(f"  Waybar style.css bulunamadı: {style_path}")
                return False

            with open(style_path, 'r') as f:
                content = f.read()

            # Renk değişkenlerini güncelle
            import re
            color_mappings = {
                'bg': self.palette['bg'],
                'bg0': self.palette.get('bg0', self.palette['bg']),
                'bg1': self.palette.get('bg1', self.palette['bg']),
                'bg2': self.palette['bg2'],
                'fg': self.palette['fg'],
                'red': self.palette['red'],
                'orange': self.palette['orange'],
                'yellow': self.palette['yellow'],
                'green': self.palette['green'],
                'aqua': self.palette['aqua'],
                'blue': self.palette['blue'],
                'purple': self.palette['purple'],
                'gray': self.palette.get('gray', self.palette['fg']),
            }

            for color_name, color_value in color_mappings.items():
                # @define-color name #hex; formatını güncelle
                pattern = rf'(@define-color\s+{color_name}\s+)#[0-9a-fA-F]{{6}};'
                replacement = rf'\g<1>{color_value};'
                content = re.sub(pattern, replacement, content)

            with open(style_path, 'w') as f:
                f.write(content)

            print(f"  Waybar style.css güncellendi")

            # Waybar'ı yeniden başlat
            subprocess.run(['pkill', 'waybar'], capture_output=True)
            subprocess.Popen(['waybar'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            print("  Waybar yeniden başlatıldı")
            return True

        except Exception as e:
            print(f"  Waybar tema uygulama hatası: {e}")
            return False

