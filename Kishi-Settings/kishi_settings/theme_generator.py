    def apply_wlogout_theme(self):
        """Wlogout temasını uygula - style.css'deki renkleri güncelle"""
        wlogout_style = f"{self.config_path}/wlogout/style.css"

        try:
            if not os.path.exists(wlogout_style):
                print(f"  Wlogout style.css bulunamadı: {wlogout_style}")
                return False

            with open(wlogout_style, 'r') as f:
                content = f.read()

            import re
            
            # Wlogout'taki renkleri güncelle
            # background-color: rgba(40, 40, 40, 0.85) -> yeni bg rengi
            bg_rgb = self._hex_to_rgb(self.palette['bg'])
            content = re.sub(
                r'background-color:\s*rgba\(\d+,\s*\d+,\s*\d+,\s*[\d.]+\)',
                f'background-color: rgba({bg_rgb[0]}, {bg_rgb[1]}, {bg_rgb[2]}, 0.85)',
                content
            )

            # background-color: #hex -> yeni bg rengi
            content = re.sub(
                r'(button\s*\{[^}]*background-color:\s*)#[0-9a-fA-F]{6}',
                rf'\g<1>{self.palette["bg"]}',
                content,
                flags=re.DOTALL
            )

            # color: #ebdbb2 -> yeni fg rengi  
            content = re.sub(
                r'(color:\s*)#ebdbb2',
                rf'\g<1>{self.palette["fg"]}',
                content
            )

            # border: 3px solid #hex -> yeni accent rengi
            content = re.sub(
                r'(border:\s*\d+px\s+solid\s+)#[0-9a-fA-F]{6}',
                rf'\g<1>{self.palette["yellow"]}',
                content
            )

            # button:hover background-color
            content = re.sub(
                r'(button:hover\s*\{[^}]*background-color:\s*)#[0-9a-fA-F]{6}',
                rf'\g<1>{self.palette["yellow"]}',
                content,
                flags=re.DOTALL
            )

            with open(wlogout_style, 'w') as f:
                f.write(content)

            print(f"  Wlogout style.css güncellendi")
            return True

        except Exception as e:
            print(f"  Wlogout tema uygulama hatası: {e}")
            return False

